"""Render PRD.md, Technical_Approach.md, Design.md and minutes.md from the canonical specification."""

from __future__ import annotations

from datetime import date

from engineering_council.models import (
    AgentProposal,
    AgentReconsideration,
    AgentRebuttal,
    AgentReview,
    Answer,
    Decision,
    Dispute,
    MeetingInput,
    QuestionCuration,
    RepoSnapshot,
    Spec,
)


def esc(text: object) -> str:
    return str(text).replace("|", "\\|").replace("\r", "").replace("\n", " ").strip()


def table(headers: list[str], rows: list[list[object]]) -> str:
    if not rows:
        return "_None._\n"
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(esc(c) for c in r) + " |" for r in rows]
    return "\n".join(out) + "\n"


def bullets(items: list[str], empty: str = "_None recorded._") -> str:
    return "\n".join(f"- {i}" for i in items) + "\n" if items else empty + "\n"


def numbered(items: list[str]) -> str:
    return "\n".join(f"{n}. {i}" for n, i in enumerate(items, 1)) + "\n" if items else "_None._\n"


def header(title: str, spec: Spec, purpose: str) -> str:
    return (
        f"# {title} — {spec.project_name}\n\n"
        f"**Status:** Draft specification generated by Engineering Council on {date.today().isoformat()}. "
        f"Nothing described here has been implemented or tested.\n\n_{purpose}_\n\n"
    )


def _dec_refs(ids: list[str]) -> str:
    return ", ".join(ids) if ids else "—"


# --------------------------------------------------------------------------- PRD


def render_prd(spec: Spec) -> str:
    fr = [r for r in spec.requirements if r.kind == "FUNCTIONAL" and r.in_scope]
    nfr = [r for r in spec.requirements if r.kind == "NON_FUNCTIONAL" and r.in_scope]
    deferred = [r for r in spec.requirements if not r.in_scope]
    by_req: dict[str, list] = {}
    for a in spec.acceptance_criteria:
        by_req.setdefault(a.requirement_id, []).append(a)

    s = header("PRD", spec, "What should be built and how success is measured.")
    s += f"## 1. Executive Summary\n\n{spec.summary}\n\n"
    s += f"## 2. Problem and Target Users\n\n{spec.problem}\n\n"
    for p in spec.personas:
        s += f"### {p.name}\n\n{p.description}\n\n" + (f"Goals:\n{bullets(p.goals)}\n" if p.goals else "")
    s += "## 3. Goals and Non-Goals\n\n### Goals\n\n" + numbered(spec.goals)
    s += "\n### Non-Goals\n\n" + bullets(spec.non_goals) + "\n"
    s += "## 4. Scope and User Journeys\n\n### In scope\n\n" + bullets(spec.scope_in)
    s += "\n### Out of scope\n\n" + bullets(spec.scope_out) + "\n"
    for j in spec.journeys:
        s += f"### Journey: {j.name}\n\n_Persona: {j.persona}_\n\n{numbered(j.steps)}\n"
    s += "## 5. Requirements\n\n### Functional requirements\n\n"
    s += table(["ID", "Title", "Description", "Priority", "Decisions"], [[r.id, r.title, r.description, r.priority, _dec_refs(r.decision_ids)] for r in fr])
    s += "\n### Non-functional requirements\n\n"
    s += table(["ID", "Title", "Description", "Priority", "Decisions"], [[r.id, r.title, r.description, r.priority, _dec_refs(r.decision_ids)] for r in nfr])
    if deferred:
        s += "\n### Deferred (not in the MVP)\n\n" + table(["ID", "Title", "Description"], [[r.id, r.title, r.description] for r in deferred])
    s += "\n## 6. Acceptance Criteria\n\n"
    for r in [*fr, *nfr]:
        crit = by_req.get(r.id, [])
        s += f"### {r.id} — {r.title}\n\n"
        if not crit:
            s += "_No acceptance criteria recorded._\n\n"
        for a in crit:
            s += f"- **{a.id}**\n  - **Given** {a.given}\n  - **When** {a.when}\n  - **Then** {a.then}\n"
        s += "\n"
    s += "## 7. Risks, Assumptions, Dependencies and Open Questions\n\n### Risks\n\n" + bullets(spec.risks)
    s += "\n### Assumptions\n\n" + bullets(spec.assumptions)
    s += "\n### Dependencies\n\n" + bullets(spec.dependencies)
    s += "\n### Open questions\n\n" + bullets(spec.open_questions, "_No open questions._") + "\n"
    s += f"## 8. MVP Boundary and Success Metrics\n\n{spec.mvp_boundary}\n\n### Success metrics\n\n" + bullets(spec.success_metrics)
    s += "\n### Release checklist\n\n"
    s += "\n".join(f"- [ ] {a.id}: {a.then}" for a in spec.acceptance_criteria[:40]) + "\n"
    return s


# --------------------------------------------------------------------------- Technical approach


def render_decision(d: Decision) -> str:
    s = f"### {d.decision_id} — {d.statement}\n\n**Status:** {d.status}  \n**Chosen:** {d.chosen_option}  \n**Rationale:** {d.rationale}\n\n"
    if d.alternatives_considered:
        s += "**Alternatives considered:**\n" + bullets(d.alternatives_considered)
    if d.rejected_alternatives:
        s += "\n**Rejected:**\n" + "\n".join(f"- ~~{r.option}~~ — {r.reason}" for r in d.rejected_alternatives) + "\n"
    if d.evidence:
        s += "\n**Evidence:**\n" + bullets(d.evidence)
    if d.remaining_uncertainty:
        s += "\n**Remaining uncertainty:**\n" + bullets(d.remaining_uncertainty)
    links = []
    if d.requirement_ids:
        links.append("Requirements: " + ", ".join(d.requirement_ids))
    if d.dispute_ids:
        links.append("Settles disputes: " + ", ".join(d.dispute_ids))
    return s + ("\n_" + "; ".join(links) + "_\n" if links else "") + "\n"


def render_technical(spec: Spec) -> str:
    s = header("Technical Approach", spec, "How the system is organised and built.")
    s += "## 1. Recommended Architecture and Rationale\n\n" + spec.summary + "\n\n"
    s += "## 2. Technology Choices and Constraints\n\n"
    s += table(["Concern", "Choice", "Rationale"], [[t.concern, t.choice, t.rationale] for t in spec.tech_choices]) + "\n"
    s += "## 3. Module Responsibilities and Dependency Direction\n\n"
    s += table(["Component", "Path", "Responsibility", "Depends on", "Requirements"], [[c.name, c.path, c.responsibility, ", ".join(c.depends_on) or "—", ", ".join(c.requirement_ids) or "—"] for c in spec.components])
    edges = [f"{c.name} → {d}" for c in spec.components for d in c.depends_on]
    s += "\nDependency direction (no cycles):\n" + bullets(edges, "_Components have no inter-dependencies._") + "\n"
    s += "## 4. Data Flow and Runtime Flows\n\n"
    for f in spec.runtime_flows:
        s += f"### {f.name}\n\n{numbered(f.steps)}\n"
    s += "## 5. Error Handling, Retries, Timeouts and Observability\n\n### Failure handling\n\n" + bullets(spec.failure_handling)
    s += "\n### Observability\n\n" + bullets(spec.observability) + "\n"
    s += "## 6. Security and Privacy\n\n" + bullets(spec.security) + "\n"
    s += "## 7. Testing Strategy and Verification\n\n" + bullets(spec.testing)
    s += "\n### Verification commands\n\n"
    s += ("```text\n" + "\n".join(spec.verification_commands) + "\n```\n") if spec.verification_commands else "_Proposed: no exact commands are known yet._\n"
    s += "\n## 8. Implementation Sequence\n\n"
    for st in sorted(spec.implementation_sequence, key=lambda x: x.order):
        dep = f" _(after step {', '.join(map(str, st.depends_on))})_" if st.depends_on else ""
        s += f"{st.order}. **{st.title}**{dep} — {st.details}\n"
    s += "\n## 9. Decision Records\n\n" + ("".join(render_decision(d) for d in spec.decisions) or "_None._\n")
    open_d = [d for d in spec.decisions if d.status != "DECIDED"]
    s += "## 10. Unresolved and Provisional Trade-offs\n\n"
    s += bullets([f"{d.decision_id} [{d.status}]: {d.statement} — {'; '.join(d.remaining_uncertainty) or 'needs confirmation'}" for d in open_d], "_All decisions are DECIDED._")
    return s


# --------------------------------------------------------------------------- Design


def render_design(spec: Spec) -> str:
    s = header("Design", spec, "Concrete contracts, interfaces, data structures and project layout.")
    s += f"## 1. Canonical Directory Tree\n\n```text\n{spec.directory_tree.strip()}\n```\n\n"
    s += "## 2. Components and Interfaces\n\n"
    s += table(["Component", "Path", "Responsibility", "Depends on"], [[c.name, c.path, c.responsibility, ", ".join(c.depends_on) or "—"] for c in spec.components]) + "\n"
    if spec.data_entities:
        s += "## 3. Data Model\n\n"
        for e in spec.data_entities:
            s += f"### {e.name}\n\n{e.description}\n\n{bullets(e.fields)}\n"
    if spec.contracts:
        s += "## 4. Contracts\n\n"
        for k in spec.contracts:
            s += f"### {k.name} ({k.kind})\n\n```text\n{k.signature}\n```\n\n"
            if k.request:
                s += f"**Request / input:** {k.request}\n\n"
            if k.response:
                s += f"**Response / output:** {k.response}\n\n"
            if k.errors:
                s += "**Errors:**\n" + bullets(k.errors) + "\n"
            if k.requirement_ids:
                s += f"_Requirements: {', '.join(k.requirement_ids)}_\n\n"
    if spec.ui_notes.strip():
        s += "## 5. UI Hierarchy and State Flows\n\n" + spec.ui_notes.strip() + "\n\n"
    s += "## 6. Error States\n\n" + table(["Code", "Condition", "Handling"], [[e.code, e.condition, e.handling] for e in spec.error_states]) + "\n"
    s += "## 7. Validation Rules\n\n" + bullets(spec.validation_rules) + "\n"
    s += "## 8. Configuration and Environment Variables\n\n"
    s += table(["Name", "Description", "Default", "Required"], [[v.name, v.description, v.default or "—", "yes" if v.required else "no"] for v in spec.config_vars]) + "\n"
    s += "## 9. Traceability\n\n"
    rows = []
    for r in spec.requirements:
        comps = [c.name for c in spec.components if r.id in c.requirement_ids]
        contracts = [k.name for k in spec.contracts if r.id in k.requirement_ids]
        acs = [a.id for a in spec.acceptance_criteria if a.requirement_id == r.id]
        rows.append([r.id, ", ".join(comps) or "—", ", ".join(contracts) or "—", ", ".join(acs) or "—", _dec_refs(r.decision_ids)])
    s += table(["Requirement", "Components", "Contracts", "Acceptance", "Decisions"], rows)
    return s


# --------------------------------------------------------------------------- Meeting minutes


def render_minutes(
    inp: MeetingInput,
    snap: RepoSnapshot,
    proposals: dict[str, AgentProposal],
    missing: list[str],
    reviews: dict[str, AgentReview],
    formal: list[Dispute],
    nitpicks: list[Dispute],
    rebuttals: dict[str, AgentRebuttal],
    curation: QuestionCuration,
    answers: list[Answer],
    decisions: list[Decision],
    warnings: list[str],
    reconsiderations: dict[str, AgentReconsideration] | None = None,
) -> str:
    s = f"# Meeting Minutes — {inp.project_name}\n\n**Date:** {date.today().isoformat()}\n\n"
    s += f"**Attendees:** {', '.join(proposals)}" + (f"  \n**Absent (failed to contribute):** {', '.join(missing)}" if missing else "") + "\n\n"
    s += f"## Agenda input\n\n{inp.problem}\n\n**Constraints:**\n{bullets(inp.constraints)}\n"
    s += f"**Context:** {snap.mode}" + (f" — {snap.source}; technologies: {', '.join(snap.technologies) or 'none detected'}" if snap.mode == "existing" else " project (no repository)") + "\n\n"
    s += "## Round 1 — Independent proposals\n\n_Each member prepared alone and had not seen the others' work._\n\n"
    for a, p in proposals.items():
        s += f"### {a}\n\n**Thesis:** {p.thesis}\n\n**Components:**\n" + bullets([f"{c.name}: {c.approach}" for c in p.components])
        if p.trade_offs:
            s += "\n**Trade-offs:**\n" + bullets([f"{t.choice} — gains: {t.gain}; costs: {t.cost}" for t in p.trade_offs])
        s += "\n**Risks:**\n" + bullets(p.risks) + "\n"
    s += "## Round 2 — Adversarial review\n\n"
    for a, r in reviews.items():
        s += f"### {a}\n\n{r.summary or '_No summary._'}\n\n"
        if r.endorsements:
            s += "**Wants adopted from others:**\n" + bullets(r.endorsements) + "\n"
        if r.no_material_objection and not r.disputes:
            s += "_NO_MATERIAL_OBJECTION._\n\n"
    s += "### Formal disputes (CRITICAL / MAJOR)\n\n"
    s += table(["ID", "Severity", "From → To", "Category", "Claim", "Failure mechanism", "Counterproposal"], [[d.dispute_id, d.severity, f"{d.source_agent} → {d.target_agent}", d.category, d.claim, d.failure_mechanism, d.counterproposal] for d in formal])
    if nitpicks:
        s += "\n### Retained nitpicks (non-blocking)\n\n" + bullets([f"{d.dispute_id} ({d.source_agent} → {d.target_agent}): {d.claim}" for d in nitpicks])
    s += "\n## Round 3 — Rebuttals\n\n"
    rows = [[r.dispute_id, a, r.stance, r.response, r.revised_position or "—"] for a, rb in rebuttals.items() for r in rb.responses]
    s += table(["Dispute", "Responder", "Stance", "Response", "Revised position"], rows) + "\n"
    s += "## Human decision gate\n\n"
    if curation.resolved_internally:
        s += "Resolved internally by the council:\n" + bullets(curation.resolved_internally) + "\n"
    s += (table(["Question", "Answer", "How"], [[a.question, a.answer, a.source] for a in answers]) if answers else "_No material questions were needed._\n") + "\n"
    if reconsiderations:
        s += "## Round 4 — Re-discussion after the human's answers\n\n"
        for a, r in reconsiderations.items():
            s += f"### {a}\n\n**Impact of the answers:** {r.answer_impact or '—'}\n\n"
            if r.position_changes:
                s += "**Changed:**\n" + bullets([f"{c.topic}: {c.change} (because {c.reason})" for c in r.position_changes])
            if r.unchanged:
                s += "**Held:**\n" + bullets(r.unchanged)
            if r.new_conflicts:
                s += "**New conflicts:**\n" + bullets([f"with {n.with_agent}: {n.issue} (position: {n.my_position})" for n in r.new_conflicts])
            if r.advice_to_arbiter:
                s += "**Advice to the arbiter:**\n" + bullets(r.advice_to_arbiter)
            s += "\n"
    s += "## Decisions\n\n" + table(["ID", "Status", "Decision", "Chosen", "Rejected"], [[d.decision_id, d.status, d.statement, d.chosen_option, "; ".join(r.option for r in d.rejected_alternatives) or "—"] for d in decisions])
    if warnings:
        s += "\n## Warnings\n\n" + bullets(warnings)
    return s
